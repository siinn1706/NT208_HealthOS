/** Fuzzy search ingredients by Vietnamese or English name */
export function searchIngredients(query: string): IngredientItem[] {
  if (!query || query.trim().length === 0) return INGREDIENTS.slice(0, 8);
  const q = query.toLowerCase().trim();
  return INGREDIENTS.filter(
    (item) =>
      item.name_vi.toLowerCase().includes(q) ||
      item.name_en.toLowerCase().includes(q)
  ).slice(0, 10);
}

/** Look up ingredient by exact name (case-insensitive) */
export function findIngredient(name: string): IngredientItem | undefined {
  const n = name.toLowerCase().trim();
  return INGREDIENTS.find(
    (item) =>
      item.name_vi.toLowerCase() === n ||
      item.name_en.toLowerCase() === n
  );
}

